// Generates site/examples.generated.ts: the examples that site/worker.ts
// serves at /<slug>/ on flareosaur.mikepage.nl.
//
// An example is served when it needs no bindings, or only `var:` bindings
// (their demo values are passed in as its env). Examples that need storage,
// queues, Durable Objects or a stubbed upstream run locally only and are
// listed on the index page with a link to their source.

import { Effect, FileSystem } from "effect"
import { type Example, loadExamples } from "./Examples.ts"
import { ROOT } from "./Port.ts"

const OUT = `${ROOT}/site/examples.generated.ts`

/** The `var:` bindings of an example, or None when it needs anything else. */
const servedVars = (example: Example): Record<string, string> | undefined => {
  const vars: Record<string, string> = {}
  for (const binding of example.bindings) {
    const [kind, rest = ""] = binding.split(/:(.*)/s)
    if (kind !== "var") return undefined
    const [name, ...value] = rest.split("=")
    vars[name!] = value.join("=")
  }
  return vars
}

const identifier = (slug: string) => `example_${slug.replaceAll(/[^a-zA-Z0-9]/g, "_")}`

export const generateSite = Effect.fnUntraced(function*() {
  const fs = yield* FileSystem.FileSystem
  const examples = yield* loadExamples()
  const served = examples.flatMap((e) => {
    const vars = servedVars(e)
    return vars && !e.checks.every((c) => c === "none") ? [{ example: e, vars }] : []
  })
  const servedSlugs = new Set(served.map((s) => s.example.slug))
  const lines = [
    "// Generated by `npm run site`. Do not edit.",
    "",
    'import type { WorkerHandler } from "@mikepage/flareosaur/workers/worker"',
    ...served.map(({ example }) => `import ${identifier(example.slug)} from "../examples/${example.slug}.ts"`),
    "",
    "export interface SiteExample {",
    "  readonly slug: string",
    "  readonly title: string",
    "  readonly group: string",
    "  readonly summary: string",
    "  readonly handler: WorkerHandler | undefined",
    "  readonly vars: Readonly<Record<string, string>>",
    "}",
    "",
    "export const examples: ReadonlyArray<SiteExample> = [",
    ...examples.map((e) => {
      const summary = e.description.split("\n\n")[0]!.replace(/\s+/g, " ")
      const fields = [
        `slug: ${JSON.stringify(e.slug)}`,
        `title: ${JSON.stringify(e.title)}`,
        `group: ${JSON.stringify(e.group)}`,
        `summary: ${JSON.stringify(summary)}`,
        `handler: ${servedSlugs.has(e.slug) ? identifier(e.slug) : "undefined"}`,
        `vars: ${JSON.stringify(served.find((s) => s.example.slug === e.slug)?.vars ?? {})}`,
      ]
      return `  { ${fields.join(", ")} },`
    }),
    "]",
    "",
  ]
  yield* fs.writeFileString(OUT, lines.join("\n"))
  return { served: served.length, total: examples.length }
})
